  function item(it) {
    const d = U.el('details', 'formula');
    d.style.marginBottom = '6px';
    const s = U.el('summary');
    s.innerHTML = '<b>' + U.escape(it.q) + '</b> <span class="tiny">— ' + U.escape(it.a) + '</span>';
    d.appendChild(s);
    const b = U.el('div', 'formula-body');
    b.innerHTML = it.body;
    if (it.formula) {
      const f = App.formula(it.formula, '수식 보기');
      f.style.marginTop = '10px';
      b.appendChild(f);
    }
    if (it.where) {
      const btn = U.el('button', 'btn sm', '이 사이트에서 보기 →');
      btn.style.marginTop = '10px';
      btn.addEventListener('click', function () { App.go(it.where); });
      b.appendChild(btn);
    }
    d.appendChild(b);
    return d;
  }

